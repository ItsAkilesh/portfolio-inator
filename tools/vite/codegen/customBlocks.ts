/**
 * File: customBlocks.ts
 * Purpose: Discovers custom block types in src/blocks/custom/<name>/ (a schema.ts exporting `schema`
 *          and a Block.tsx default-exporting the component) and generates the two modules that plug
 *          them into the content schema and the page renderer. Pure generation plus a folder scan.
 * Author: Akilesh
 * Date: 2026-10-21
 */
import { existsSync } from "node:fs";
import { readdir } from "node:fs/promises";
import { join } from "node:path";

const NAME = /^[a-z][a-zA-Z0-9]*$/;
export const SCHEMAS_FILE = "schemas.generated.ts";
export const COMPONENTS_FILE = "components.generated.ts";

const header = (file: string, purpose: string) => `/**
 * File: ${file}
 * Purpose: GENERATED by tools/vite/codegen from the folders in src/blocks/custom; do not edit.
 *          ${purpose}
 * Author: Akilesh
 * Date: 2026-10-21
 */
`;

/** Folder names that hold a complete custom block, sorted. */
export async function findCustomBlocks(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  return entries
    .filter((e) => e.isDirectory() && NAME.test(e.name))
    .filter(
      (e) =>
        existsSync(join(dir, e.name, "schema.ts")) &&
        existsSync(join(dir, e.name, "Block.tsx")),
    )
    .map((e) => e.name)
    .sort();
}

export function renderSchemasModule(names: readonly string[]): string {
  const imports = names
    .map((n) => `import { schema as ${n} } from "./${n}/schema";\n`)
    .join("");
  return `${header(SCHEMAS_FILE, "Schemas of the custom block types, added to the content's block union.")}${imports}
export const CUSTOM_BLOCK_SCHEMAS = [${names.join(", ")}] as const;
`;
}

export function renderComponentsModule(names: readonly string[]): string {
  const entries = names
    .map((n) => `  ${n}: lazy(() => import("./${n}/Block")),\n`)
    .join("");
  return `${header(COMPONENTS_FILE, "Code-split renderers of the custom block types, by type.")}import { lazy, type ComponentType, type LazyExoticComponent } from "react";
import type { BlockOf, CustomBlockType } from "../../types/portfolio";

export const CUSTOM_BLOCK_COMPONENTS: {
  readonly [K in CustomBlockType]: LazyExoticComponent<ComponentType<{ readonly block: BlockOf<K> }>>;
} = {
${entries}};
`;
}
